/** Drawn for any character the font does not have. */
export const UNKNOWN_GLYPH: Glyph = [".....", "#####", "#...#", "#...#", "#...#", "#####", "....."];

/** Glyph for a character: case-insensitive, unknown characters map to a box. */
export function glyphFor(ch: string): Glyph {
  const direct = FONT_5X7[ch];
  if (direct !== undefined) return direct;
  const upper = FONT_5X7[ch.toUpperCase()];
  return upper ?? UNKNOWN_GLYPH;
}

/** Whether the font has a glyph for the character (after uppercasing). */
export function hasGlyph(ch: string): boolean {
  return FONT_5X7[ch] !== undefined || FONT_5X7[ch.toUpperCase()] !== undefined;
}
